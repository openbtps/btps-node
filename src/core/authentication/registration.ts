/*
 * BTPS 1.1 device registration bound to the identity: a device is
 * registered only on a one-time registration token issued to the owner of
 * the identity, and it is bound to exactly that identity. Also the rule that
 * stops a forged agent message: an agent artifact is verified only with an
 * agent's own trust record, never with a record between two identities.
 */

import { computeTrustId } from '@core/trust/index.js';
import type { BTPTrustRecord } from '@core/trust/types.js';
import type { AbstractTrustStore } from '@core/trust/storage/AbstractTrustStore.js';
import { base64ToPem } from '@core/utils/index.js';
import {
  BTP_ERROR_REGISTRATION_IDENTITY_MISMATCH,
  BTP_ERROR_REGISTRATION_TOKEN_INVALID,
  BTP_ERROR_REGISTRATION_TOKEN_MISSING,
  BTP_ERROR_REGISTRATION_TOKEN_USED,
  BTP_ERROR_REGISTRATION_UNAVAILABLE,
} from '@core/error/constant.js';
import { BTPErrorException } from '@core/error/index.js';
import type { BTPError } from '@core/error/types.js';
import type { BTPsTokenDocument, TokenStore } from './types.js';

/** Why a registration was refused. */
export type BTPRegistrationRefusal =
  /** The server has no token store. */
  | 'unavailable'
  /** No token in the request. */
  | 'missing'
  /** The request names two identities, or the token is another identity's. */
  | 'identity-mismatch'
  /** No unexpired token with this value for this identity. */
  | 'invalid'
  /** The token was already used. */
  | 'used';

export type BTPRegistrationResult =
  | { ok: true; identity: string; token: BTPsTokenDocument }
  | { ok: false; reason: BTPRegistrationRefusal; error: BTPErrorException };

const REFUSAL_ERRORS = {
  unavailable: BTP_ERROR_REGISTRATION_UNAVAILABLE,
  missing: BTP_ERROR_REGISTRATION_TOKEN_MISSING,
  'identity-mismatch': BTP_ERROR_REGISTRATION_IDENTITY_MISMATCH,
  invalid: BTP_ERROR_REGISTRATION_TOKEN_INVALID,
  used: BTP_ERROR_REGISTRATION_TOKEN_USED,
} as const;

/** The errors a registration can be refused with, one per reason. */
export const REGISTRATION_ERRORS: readonly BTPError[] = Object.values(REFUSAL_ERRORS);

const refuse = (
  reason: BTPRegistrationRefusal,
  meta: Record<string, unknown>,
): BTPRegistrationResult => ({
  ok: false,
  reason,
  error: new BTPErrorException(REFUSAL_ERRORS[reason], { cause: reason, meta }),
});

const sameIdentity = (a: string, b: string) => a.toLowerCase() === b.toLowerCase();

/**
 * Takes a registration token, once, for an `auth.request`.
 *
 * - `identity` is the request document's `identity`, and `to` the
 *   artifact's `to`: they must be the same identity.
 * - The token is looked up under that identity, the key `storeAuthToken`
 *   stored it under, and consumed atomically: of two devices racing with one
 *   token, one is accepted and the other refused as `used`.
 * - The token found must have been issued to that identity.
 *
 * With no token store, every registration is refused (`unavailable`).
 */
export async function consumeRegistrationToken(
  tokenStore: TokenStore | undefined,
  request: { identity: string; to: string; authToken: string },
): Promise<BTPRegistrationResult> {
  const { identity, to, authToken } = request;
  const meta = { identity, to };
  if (!tokenStore) return refuse('unavailable', meta);
  if (typeof authToken !== 'string' || authToken.trim() === '') return refuse('missing', meta);
  if (typeof identity !== 'string' || typeof to !== 'string' || !sameIdentity(identity, to)) {
    return refuse('identity-mismatch', meta);
  }

  const result = await tokenStore.consume(identity, authToken);
  if (result.status === 'used') return refuse('used', meta);
  if (result.status !== 'consumed') return refuse('invalid', meta);
  if (!sameIdentity(result.record.userIdentity, identity)) {
    return refuse('identity-mismatch', { ...meta, tokenIdentity: result.record.userIdentity });
  }
  return { ok: true, identity: result.record.userIdentity, token: result.record };
}

/**
 * Whether `agentId` can name a device agent. An agent id is generated by the
 * server (`BtpsAuthentication.generateAgentId`, `btps_ag_<uuid>`) and is
 * never an identity: an identity has a `$`, an agent id has none.
 */
export const isAgentId = (agentId: unknown): agentId is string =>
  typeof agentId === 'string' && agentId.length > 0 && !agentId.includes('$');

/** Why no agent key was found for an agent artifact. */
export type BTPAgentKeyRefusal =
  /** `agentId` is not an agent id: it names an identity, or is empty. */
  | 'not-an-agent'
  /** No trust record for `(agentId, to)`. */
  | 'no-record'
  /** The record under that id is not this agent's binding to `to`. */
  | 'record-mismatch';

export type BTPAgentKeyResult =
  | { ok: true; publicKeyPem: string; record: BTPTrustRecord }
  | { ok: false; reason: BTPAgentKeyRefusal };

/**
 * The key an agent artifact other than `auth.request` is verified with: the
 * one in the agent's own trust record, `(agentId → to)`, as `createAgent`
 * wrote it.
 *
 * The trust store also holds records between two identities, under the same
 * `computeTrustId(from, to)`. An artifact whose `agentId` is a correspondent's
 * identity would otherwise be verified with that correspondent's key and
 * trusted by their trust record, letting them act as the receiver's device.
 */
export async function resolveAgentKey(
  trustStore: AbstractTrustStore<BTPTrustRecord>,
  artifact: { agentId: string; to: string },
): Promise<BTPAgentKeyResult> {
  const { agentId, to } = artifact;
  if (!isAgentId(agentId)) return { ok: false, reason: 'not-an-agent' };
  const record = await trustStore.getById(computeTrustId(agentId, to));
  if (!record) return { ok: false, reason: 'no-record' };
  if (record.senderId !== agentId || !sameIdentity(record.receiverId, to)) {
    return { ok: false, reason: 'record-mismatch' };
  }
  return { ok: true, publicKeyPem: base64ToPem(record.publicKeyBase64), record };
}
